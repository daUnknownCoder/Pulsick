-- Run this once in Supabase Dashboard → SQL Editor for this project.
-- It creates the persistent directory, accounts and message storage used by the app.

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  display_name text not null default 'Pulsick member',
  email text,
  role text not null default 'user' check (role in ('user', 'creator')),
  avatar_url text,
  bio text not null default '',
  location text not null default '',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.creators (
  id text primary key,
  name text not null,
  handle text not null unique,
  specialization text not null,
  status text not null,
  avatar_url text,
  gradient text,
  profile_id uuid unique references public.profiles(id) on delete set null,
  created_at timestamptz not null default now()
);

alter table public.profiles add column if not exists bio text not null default '';
alter table public.profiles add column if not exists location text not null default '';
alter table public.creators add column if not exists profile_id uuid unique references public.profiles(id) on delete set null;

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  creator_id text not null references public.creators(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  sender text not null check (sender in ('you', 'creator', 'you-creator')),
  text text not null default '',
  image text not null default '',
  image_name text not null default '',
  created_at timestamptz not null default now(),
  constraint messages_have_content check (length(trim(text)) > 0 or length(image) > 0)
);

create index if not exists messages_user_creator_created_at_idx on public.messages (user_id, creator_id, created_at);

-- Make profile creation reliable even when email confirmation is enabled and
-- the browser does not yet have an authenticated session.
create or replace function public.create_profile_for_new_user()
returns trigger
language plpgsql
security definer set search_path = public
as $$
begin
  insert into public.profiles (id, display_name, email, role)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'display_name', split_part(new.email, '@', 1), 'Pulsick member'),
    new.email,
    coalesce(new.raw_user_meta_data ->> 'role', 'user')
  )
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists create_profile_on_auth_user on auth.users;
create trigger create_profile_on_auth_user
  after insert on auth.users
  for each row execute procedure public.create_profile_for_new_user();

alter table public.profiles enable row level security;
alter table public.creators enable row level security;
alter table public.messages enable row level security;

drop policy if exists "Profiles are readable by signed in users" on public.profiles;
drop policy if exists "Users can create their profile" on public.profiles;
drop policy if exists "Users can update their profile" on public.profiles;
drop policy if exists "Creator directory is public" on public.creators;
drop policy if exists "Users can read their messages" on public.messages;
drop policy if exists "Users can send their messages" on public.messages;

create policy "Profiles are readable by signed in users" on public.profiles for select to authenticated using (true);
create policy "Users can create their profile" on public.profiles for insert to authenticated with check (auth.uid() = id);
create policy "Users can update their profile" on public.profiles for update to authenticated using (auth.uid() = id);
create policy "Creator directory is public" on public.creators for select using (true);
create policy "Users can read their messages" on public.messages for select to authenticated using (auth.uid() = user_id);
create policy "Users can send their messages" on public.messages for insert to authenticated with check (auth.uid() = user_id);

-- Allow live message updates in the client after this schema has been applied.
do $$ begin
  if not exists (
    select 1 from pg_publication_tables
    where pubname = 'supabase_realtime' and schemaname = 'public' and tablename = 'messages'
  ) then
    alter publication supabase_realtime add table public.messages;
  end if;
end $$;

